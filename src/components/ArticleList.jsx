import Article from "./Article";

// ArticleList: maps each post to an Article. Child of App, parent of Article.
function ArticleList({ posts }) {
  return (
    <main>
      {posts.map((post) => (
        <Article
          key={post.id}
          title={post.title}
          date={post.date}
          preview={post.preview}
        />
      ))}
    </main>
  );
}
export default ArticleList;